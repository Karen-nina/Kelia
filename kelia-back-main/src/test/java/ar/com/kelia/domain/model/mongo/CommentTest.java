package ar.com.kelia.domain.model.mongo;

import org.junit.jupiter.api.Test;

import java.time.LocalDateTime;
import java.time.ZoneId;

import static org.junit.jupiter.api.Assertions.*;

class CommentTest {

    @Test
    void shouldCreateCommentWithAutoGeneratedFields() {
        UserMongo user = new UserMongo();
        user.setUid("USR777");
        user.setUsername("juanp");
        user.setAvatar("juan.png");
        user.setDisplayName("Juan Pérez");

        Comment comment = new Comment();
        comment.setUser(user);
        comment.setContent("Muy buena publicación!");

        assertNotNull(comment.getId());
        assertTrue(comment.getId().matches("^[a-f0-9\\-]{36}$")); // UUID format

        assertEquals(user, comment.getUser());
        assertEquals("Muy buena publicación!", comment.getContent());

        LocalDateTime now = LocalDateTime.now(ZoneId.of("America/Argentina/Buenos_Aires"));
        assertNotNull(comment.getCreatedAt());
        assertTrue(comment.getCreatedAt().isBefore(now.plusSeconds(2)));
        assertTrue(comment.getCreatedAt().isAfter(now.minusSeconds(10))); // margen de seguridad
    }

    @Test
    void shouldAllowUpdatingCommentFields() {
        Comment comment = new Comment();
        UserMongo user = new UserMongo();
        user.setUid("USR888");

        comment.setUser(user);
        comment.setContent("Actualizado");
        comment.setCreatedAt(LocalDateTime.of(2023, 9, 5, 15, 0));

        assertEquals("Actualizado", comment.getContent());
        assertEquals(user, comment.getUser());
        assertEquals(LocalDateTime.of(2023, 9, 5, 15, 0), comment.getCreatedAt());
    }
}
